"""Builds responsive photo derivatives + the generated half of the media registry.
   Source: photo-source/*.jpg (the supplied pack).  Output: src/assets/photos/* and src/assets/media.gen.ts
   Run:  python3 scripts/build-photos.py      (needs Pillow with WebP + AVIF support)"""
import base64, glob, io, json, os
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC, OUT = os.path.join(ROOT, "photo-source"), os.path.join(ROOT, "src/assets/photos")
os.makedirs(OUT, exist_ok=True)
for f in glob.glob(OUT + "/*"): os.remove(f)
# Square crops that hide the wrong uniform/door branding and the third-party resort signs (see MANIFEST known issues).
CROPS = {
  "face-1": ("driver-1", (374, 20, 634, 280)), "face-2": ("driver-2", (681, 10, 941, 270)), "face-3": ("driver-3", (382, 5, 642, 265)),
  "face-4": ("driver-4", (531, 0, 791, 260)), "face-5": ("driver-5", (700, 0, 960, 260)), "face-6": ("driver-6", (838, 40, 1098, 300)),
  "guest-couple": ("pax-couple", (445, 205, 745, 505)), "guest-family": ("pax-family", (420, 235, 760, 575)),
  "guest-solo": ("pax-solo", (340, 20, 700, 380)), "guest-business": ("pax-business", (640, 215, 960, 535)),
}
meta = {}
def save(im, name, w):
    if im.width > w: im = im.resize((w, round(im.height * w / im.width)), Image.LANCZOS)
    im.save(f"{OUT}/{name}-{w}.avif", quality=52, speed=6); im.save(f"{OUT}/{name}-{w}.webp", quality=74, method=5)
    return im
def blur(im):
    t = im.copy(); t.thumbnail((20, 20)); b = io.BytesIO(); t.save(b, "JPEG", quality=45)
    avg = im.resize((1, 1)).getpixel((0, 0))
    return "data:image/jpeg;base64," + base64.b64encode(b.getvalue()).decode(), "#%02x%02x%02x" % avg
for path in sorted(glob.glob(SRC + "/*.jpg")):
    name = os.path.basename(path)[:-4]; im = Image.open(path).convert("RGB")
    full = im.width; sizes = [640, full]
    for w in sizes: save(im, name, w)
    im.save(f"{OUT}/{name}-{full}.jpg", quality=78, optimize=True, progressive=True)
    b, c = blur(im); meta[name] = {"w": im.width, "h": im.height, "sizes": sizes, "blur": b, "color": c}
for name, (src, box) in CROPS.items():
    im = Image.open(f"{SRC}/{src}.jpg").convert("RGB").crop(box).resize((320, 320), Image.LANCZOS)
    save(im, name, 320); im.save(f"{OUT}/{name}-320.jpg", quality=80, optimize=True)
    b, c = blur(im); meta[name] = {"w": 320, "h": 320, "sizes": [320], "blur": b, "color": c}
open(os.path.join(ROOT, "src/assets/media.gen.ts"), "w").write("// GENERATED by scripts/build-photos.py. Do not edit.\nexport const GEN = " + json.dumps(meta, indent=1) + " as const;\n")
print(len(meta), "slots,", len(os.listdir(OUT)), "files,", round(sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT)) / 1e6, 1), "MB")
