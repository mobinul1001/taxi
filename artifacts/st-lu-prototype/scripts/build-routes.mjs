/**
 * Turns scripts/routes.json (real road geometry from the client's map-data pack) into
 * src/assets/routes.gen.ts.
 *
 * The raw file is 570 KB: around 25,000 points, far more than the map can show. Each route is
 * simplified with Douglas-Peucker at about 6 m, which is under three pixels at the deepest zoom
 * the tiles go to (14), so the drawn road is identical and the bundle stays small.
 *
 *   node scripts/build-routes.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const EPS = 0.00006; // degrees, ~6.6m of latitude
const sqSegDist = (p, a, b) => {
  let x = a[0], y = a[1], dx = b[0] - x, dy = b[1] - y;
  if (dx !== 0 || dy !== 0) {
    const t = ((p[0] - x) * dx + (p[1] - y) * dy) / (dx * dx + dy * dy);
    if (t > 1) { x = b[0]; y = b[1]; } else if (t > 0) { x += dx * t; y += dy * t; }
  }
  return (p[0] - x) ** 2 + (p[1] - y) ** 2;
};
function simplify(pts, eps) {
  if (pts.length < 3) return pts;
  const keep = new Array(pts.length).fill(false);
  keep[0] = keep[pts.length - 1] = true;
  const stack = [[0, pts.length - 1]];
  const e2 = eps * eps;
  while (stack.length) {
    const [a, b] = stack.pop();
    let far = -1, idx = -1;
    for (let i = a + 1; i < b; i++) {
      const d = sqSegDist(pts[i], pts[a], pts[b]);
      if (d > far) { far = d; idx = i; }
    }
    if (far > e2) { keep[idx] = true; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const raw = JSON.parse(readFileSync("scripts/routes.json", "utf8"));
const dedupe = (pts) => pts.filter((p, i) => i === 0 || p[0] !== pts[i - 1][0] || p[1] !== pts[i - 1][1]);
const round = (p) => [Number(p[0].toFixed(5)), Number(p[1].toFixed(5))];

let before = 0, after = 0;
const routes = {};
for (const [key, r] of Object.entries(raw.routes)) {
  const pts = dedupe(r.coords);
  before += r.coords.length;
  const s = simplify(pts, EPS).map(round);
  after += s.length;
  routes[key] = { km: r.km, minutes: r.minutes, coords: s };
}

const out = `/* GENERATED by scripts/build-routes.mjs from the client's map-data pack — do not edit by hand.
   Real road geometry for ${Object.keys(routes).length} routes, simplified from ${before} to ${after} points. */

export interface RoadRoute { km: number; minutes: number; coords: [number, number][] }

/** Keyed by direction, e.g. "UVF-RodneyBay". Coordinates are [lat, lng]. */
export const ROAD_ROUTES: Record<string, RoadRoute> = ${JSON.stringify(routes)} as Record<string, RoadRoute>;

/** Place anchors from the same pack, [lng, lat]. */
export const ROUTE_PLACES: Record<string, [number, number]> = ${JSON.stringify(raw.places)} as Record<string, [number, number]>;
`;
writeFileSync("src/assets/routes.gen.ts", out);
console.log(`routes: ${Object.keys(routes).length}, points ${before} -> ${after}, file ${(out.length / 1024).toFixed(0)} KB`);
